import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

// Writes packages/app/src/fork-build-meta.ts with the values baked into the
// app bundle. Runs in CI (build-all-feats.yml, VERSION from the workflow) and
// locally (hooked into the root build:desktop script, VERSION unset).
function git(args) {
  return execFileSync("git", args, { encoding: "utf8" }).trim();
}

const meta = {
  version: process.env.VERSION ?? null,
  builtAt: new Date().toISOString(),
  commit: git(["rev-parse", "HEAD"]),
  commitTime: git(["log", "-1", "--format=%cI"]),
};

const body = `// AUTO-GENERATED by scripts/gen-fork-build-meta.mjs at build time. Do not edit.
export const FORK_BUILD_META = ${JSON.stringify(meta, null, 2)};
`;

writeFileSync(new URL("../packages/app/src/fork-build-meta.ts", import.meta.url), body);
console.log(
  `fork-build-meta: version=${meta.version ?? "none"} commit=${meta.commit.slice(0, 7)} time=${meta.commitTime}`,
);
